CREATE TABLE IF NOT EXISTS `Categoria` (
	`Id` INT NOT NULL AUTO_INCREMENT,
	`Descripcion` VARCHAR(255) NOT NULL,
	`Activo` BOOLEAN NOT NULL,
	PRIMARY KEY(`Id`)
);


CREATE TABLE IF NOT EXISTS `Marca` (
	`Id` INT NOT NULL AUTO_INCREMENT,
	`Descripcion` VARCHAR(255) NOT NULL,
	`Activo` BOOLEAN NOT NULL,
	PRIMARY KEY(`Id`)
);


CREATE TABLE IF NOT EXISTS `Proveedor` (
	`id` INT NOT NULL AUTO_INCREMENT,
	`cuit` VARCHAR(255) NOT NULL UNIQUE,
	`razonSocial` VARCHAR(255) NOT NULL,
	`telefono` VARCHAR(255) NOT NULL,
	`email` VARCHAR(255) NOT NULL,
	`direccion ` VARCHAR(255) NOT NULL,
	`Activo` BOOLEAN NOT NULL,
	PRIMARY KEY(`id`)
);


CREATE TABLE IF NOT EXISTS `Cliente` (
	`id` INT NOT NULL AUTO_INCREMENT,
	`documento` VARCHAR(255) NOT NULL UNIQUE,
	`nombre` VARCHAR(255) NOT NULL,
	`apellido` VARCHAR(255) NOT NULL,
	`telefono` VARCHAR(255) NOT NULL,
	`email` VARCHAR(255) NOT NULL,
	`direccion` VARCHAR(255) NOT NULL,
	`activo` BOOLEAN NOT NULL,
	PRIMARY KEY(`id`)
);


CREATE TABLE IF NOT EXISTS `Usuario` (
	`id` INT NOT NULL AUTO_INCREMENT,
	`nombreUsuario` VARCHAR(255) NOT NULL UNIQUE,
	`password` VARCHAR(255) NOT NULL,
	`email` VARCHAR(255) NOT NULL,
	`perfil` INT NOT NULL,
	`activo` BOOLEAN NOT NULL,
	`esAdministrador` BOOLEAN NOT NULL,
	PRIMARY KEY(`id`)
);


CREATE TABLE IF NOT EXISTS `Producto` (
	`id` INT NOT NULL AUTO_INCREMENT,
	`codigo` VARCHAR(255) NOT NULL UNIQUE,
	`nombre` VARCHAR(255) NOT NULL,
	`descripcion` VARCHAR(255),
	`urlImagen` VARCHAR(255),
	`idMarca` INT,
	`idCategoria` INT,
	`stockActual` INT NOT NULL,
	`stockMinimo` INT NOT NULL,
	`porcentajeGanancia` DECIMAL NOT NULL,
	`ultimoPrecioCompra` DECIMAL NOT NULL,
	`activo` BOOLEAN NOT NULL,
	PRIMARY KEY(`id`)
);


CREATE TABLE IF NOT EXISTS `productoProveedor` (
	`idProducto` INT NOT NULL AUTO_INCREMENT,
	`idProveedor` INT NOT NULL,
	PRIMARY KEY(`idProducto`, `idProveedor`)
);


CREATE TABLE IF NOT EXISTS `Compra` (
	`id` INT NOT NULL AUTO_INCREMENT,
	`fecha` DATETIME,
	`idProveedor` INT NOT NULL,
	`idUsuario` INT NOT NULL,
	`total` DECIMAL NOT NULL,
	PRIMARY KEY(`id`)
);


CREATE TABLE IF NOT EXISTS `detalleCompra` (
	`id` INT NOT NULL AUTO_INCREMENT,
	`idCompra` INT NOT NULL,
	`idProducto` INT NOT NULL,
	`cantidad` INT NOT NULL,
	`precioUnitario` DECIMAL NOT NULL,
	`subTotal` DECIMAL NOT NULL,
	PRIMARY KEY(`id`)
);


CREATE TABLE IF NOT EXISTS `Venta` (
	`id` INT NOT NULL AUTO_INCREMENT,
	`numeroFactura` VARCHAR(255) NOT NULL,
	`fecha` DATETIME NOT NULL,
	`idCliente` INT NOT NULL,
	`idUsuario` INT NOT NULL,
	`total` DECIMAL NOT NULL,
	PRIMARY KEY(`id`)
);


CREATE TABLE IF NOT EXISTS `detalleVenta` (
	`id` INT NOT NULL AUTO_INCREMENT,
